salary = 5000  # Ежемесячная зарплата
spend = 6000  # Траты за первый месяц
months = 10  # Количество месяцев, которое планируется протянуть без долгов
increase = 0.03  # Ежемесячный рост цен

# TODO Рассчитайте подушку безопасности, чтобы протянуть 10 месяцев без долгов
# Инициализируем переменные
needed_capital = 0  # Требуемая подушка безопасности
current_spend = spend  # Текущие расходы

# Проходим по всем месяцам
for month in range(1, months + 1):
    # Зарплаты не хватает на текущие расходы
    deficit = current_spend - salary

    if deficit > 0:
        # Добавляем дефицит к требуемой подушке
        needed_capital += deficit

    # Увеличиваем расходы на следующий месяц
    current_spend *= (1 + increase)

# Округляем до целого числа
needed_capital = round(needed_capital)

print(f"Подушка безопасности, чтобы протянуть {months} месяцев без долгов:", needed_capital)

