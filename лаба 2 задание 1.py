money_capital = 20000  # Подушка безопасности
salary = 5000  # Ежемесячная зарплата
spend = 6000  # Траты за первый месяц
increase = 0.05  # Ежемесячный рост цен
months = 0  # Счетчик месяцев
# TODO Посчитайте количество  месяцев, которое можно протянуть без долгов
while True:
    # Проверяем, хватит ли денег на текущий месяц
    # Доход текущего месяца: подушка безопасности + зарплата
    available_money = money_capital + salary
    if available_money >= spend:
        # Вычитаем траты из доступных денег
        money_capital = available_money - spend
        months += 1  # Увеличиваем счетчик месяцев

        # Увеличиваем расходы на следующий месяц (кроме первого месяца)
        spend *= (1 + increase)
    else:
        # Денег не хватает - выходим из цикла
        break

print("Количество месяцев, которое можно протянуть без долгов:", months)

